#!/usr/bin/env python3
"""Generate Games/ZxrPatchJs.h from the shared ZXR patch spec."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "_common"))
from gen_util import write_if_changed  # noqa: E402


def c_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen_zxr_patch_header.py <patch_spec.json> <ZxrPatchJs.h>", file=sys.stderr)
        return 2
    spec_path = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    spec = json.loads(spec_path.read_text(encoding="utf-8"))

    marker = spec["marker"]
    prefix = spec["prefix"]
    replacements = spec["replacements"]
    if len(replacements) != 3:
        raise SystemExit("Zxr patch spec must contain exactly 3 replacements")

    lines = [
        "/* Generated by gen_zxr_patch_header.py. Do not edit. */",
        "#ifndef STARRY_ZXR_PATCH_JS_H",
        "#define STARRY_ZXR_PATCH_JS_H",
        "",
        f"static const char* kZxrPatchMarker = {c_string(marker)};",
        f"static const char* kZxrPatchPrefix = {c_string(prefix)};",
        "",
    ]
    for rep in replacements:
        name = rep["name"]
        lines.append(f"static const char* kZxr_{name}_anchor = {c_string(rep['anchor'])};")
        lines.append(f"static const char* kZxr_{name}_replacement = {c_string(rep['anchor'] + rep['insert'])};")
        lines.append("")
    lines.extend([
        "#endif // STARRY_ZXR_PATCH_JS_H",
        "",
    ])
    out_path.parent.mkdir(parents=True, exist_ok=True)
    # 幂等写（见 _common/gen_util.py）：内容未变不落盘，避免刷新 mtime 触发无谓重建
    write_if_changed(out_path, "\n".join(lines), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
