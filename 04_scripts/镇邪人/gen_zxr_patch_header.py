#!/usr/bin/env python3
"""Generate Games/ZxrPatchJs.h from one or more ZXR patch specs (变体表 + 共享 insert).

2026-10-25 起：头文件不再只装「一份字面锚点」，而是**变体表**——
每个钩子一条 insert（多份 spec 必须一致）+ N 条历史锚点（b5278/ca0d4/e4278/0d1ae 一代、
d5507@vc11 一代、cb9dc 一代…）。运行时顺序：**结构派生优先**（ZxrDerive.h，不认标识符），
派生不出才逐条试这些历史锚点。

用法（新）：
    gen_zxr_patch_header.py --out Games/ZxrPatchJs.h spec1.json spec2.json ...
用法（旧，兼容）：
    gen_zxr_patch_header.py spec1.json Games/ZxrPatchJs.h
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "_common"))
from gen_util import write_if_changed  # noqa: E402

HOOK_ORDER = ("damage_and_invincible", "attack_speed", "full_screen_kill")


def c_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def load_specs(paths: list[Path]) -> tuple[str, str, dict[str, list[tuple[str, str]]]]:
    marker = None
    prefix = None
    hooks: dict[str, list[tuple[str, str]]] = {name: [] for name in HOOK_ORDER}
    for path in paths:
        spec = json.loads(path.read_text(encoding="utf-8"))
        if marker is None:
            marker = spec["marker"]
            prefix = spec["prefix"]
        elif spec["marker"] != marker or spec["prefix"] != prefix:
            raise SystemExit(f"ERROR: {path} 的 marker/prefix 与首份 spec 不一致")
        names = [r["name"] for r in spec["replacements"]]
        if sorted(names) != sorted(HOOK_ORDER):
            raise SystemExit(f"ERROR: {path} 的钩子集合不是 {HOOK_ORDER}: {names}")
        for rep in spec["replacements"]:
            entry = (rep["anchor"], rep["anchor"] + rep["insert"])
            # 同一锚点/同一替换去重（多份 spec 常常字面相同）
            if entry not in hooks[rep["name"]]:
                hooks[rep["name"]].append(entry)
    assert marker and prefix
    for name, items in hooks.items():
        if not items:
            raise SystemExit(f"ERROR: 钩子 {name} 没有任何变体")
    return marker, prefix, hooks


def main() -> int:
    argv = sys.argv[1:]
    if not argv:
        print(__doc__, file=sys.stderr)
        return 2
    if argv[0] == "--out":
        if len(argv) < 3:
            print(__doc__, file=sys.stderr)
            return 2
        out_path = Path(argv[1])
        spec_paths = [Path(p) for p in argv[2:]]
    else:  # 旧签名：<spec> <header>
        if len(argv) != 2:
            print(__doc__, file=sys.stderr)
            return 2
        spec_paths = [Path(argv[0])]
        out_path = Path(argv[1])

    marker, prefix, hooks = load_specs(spec_paths)

    lines = [
        "/* Generated by gen_zxr_patch_header.py. Do not edit. */",
        "#ifndef STARRY_ZXR_PATCH_JS_H",
        "#define STARRY_ZXR_PATCH_JS_H",
        "",
        "/* Per hook: one insert (validated identical across specs) + N historical anchors.",
        " * Runtime order: structural derive (ZxrDerive.h) first, then these variants. */",
        "struct ZxrPatchVariant {",
        "    const char* anchor;",
        "    const char* replacement;",
        "};",
        "",
        f"static const char* kZxrPatchMarker = {c_string(marker)};",
        f"static const char* kZxrPatchPrefix = {c_string(prefix)};",
        "",
    ]
    for name in HOOK_ORDER:
        items = hooks[name]
        lines.append(f"static const ZxrPatchVariant kZxrVariants_{name}[] = {{")
        for anchor, replacement in items:
            lines.append(f"    {{{c_string(anchor)}, {c_string(replacement)}}},")
        lines.append("};")
        lines.append(f"static const int kZxrVariants_{name}_n = {len(items)};")
        lines.append("")
    lines.extend([
        "#endif // STARRY_ZXR_PATCH_JS_H",
        "",
    ])
    out_path.parent.mkdir(parents=True, exist_ok=True)
    write_if_changed(out_path, "\n".join(lines), encoding="ascii")
    counts = ", ".join(f"{n}={len(hooks[n])}" for n in HOOK_ORDER)
    print(f"zxr_patch_header={out_path} variants: {counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
